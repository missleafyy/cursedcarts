#!/usr/bin/env python3
# Item shapes come from each PNG's alpha. Reads tools/item_sizes.json, writes game/shapes.js. Art is only read.
import json
from PIL import Image
import numpy as np
items=json.load(open('tools/item_sizes.json')); out={}; n=0
for k,(art,w,h) in items.items():
    a=np.asarray(Image.open(f'art/items/{art}.png').convert('RGBA'))[:,:,3]>40
    ih,iw=a.shape; sc=min(w/iw,h/ih); dw,dh=iw*sc,ih*sc; ox,oy=(w-dw)/2,(h-dh)/2
    g=[[False]*w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            x0,x1=int(max(0,(x-ox)/sc)),int(min(iw,(x+1-ox)/sc+.999)); y0,y1=int(max(0,(y-oy)/sc)),int(min(ih,(y+1-oy)/sc+.999))
            if x1>x0 and y1>y0 and a[y0:y1,x0:x1].mean()>=.18: g[y][x]=True
    if not any(map(any,g)): g=[[True]*w for _ in range(h)]
    # keep the largest connected piece so nothing can slot through the middle of an item
    seen=set(); best=[]
    for y in range(h):
        for x in range(w):
            if g[y][x] and (x,y) not in seen:
                st=[(x,y)]; seen.add((x,y)); comp=[]
                while st:
                    c=st.pop(); comp.append(c)
                    for d in ((1,0),(-1,0),(0,1),(0,-1)):
                        q=(c[0]+d[0],c[1]+d[1])
                        if 0<=q[0]<w and 0<=q[1]<h and g[q[1]][q[0]] and q not in seen: seen.add(q); st.append(q)
                if len(comp)>len(best): best=comp
    b=set(best); rows=[''.join('#' if (x,y) in b else '.' for x in range(w)) for y in range(h)]
    if any('.' in r for r in rows): out[k]=rows; n+=1
open('game/shapes.js','w').write('// generated by tools/make_shapes.py from the PNG alpha\nwindow.DATA.SHAPES = '+json.dumps(out,separators=(',',':'))+';\n')
print(len(items),'items',n,'non-rectangular')
